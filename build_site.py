"""Build the static website (docs/) so the site works with NO server and no terminal.

    python build_site.py                      today + tomorrow, refreshing yesterday's results first
    python build_site.py --dates 2026-10-26   specific days
    python build_site.py --no-refresh         skip pulling yesterday's results

It writes docs/data/<date>.json (the same JSON the live API returns), docs/data/index.json,
copies the page from frontend/ into docs/, and saves data/today/predictions_<today>.csv
for score_day.py. Needs API_FOOTBALL_KEY (in .env locally, or a GitHub secret).
The .github/workflows/daily.yml workflow runs this every morning.
"""
import argparse
import asyncio
import json
import shutil
import sys
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

from app.services.daily import get_tz, write_predictions_csv
from app.services.daily import refresh_results as shared_refresh
from app.services.day_payload import DayUnavailable, build_day_payload
from app.services.ratings_store import get_state
from app.services.sports_api import SportsAPIError, fetch_football_data

SITE_DIR = Path("docs")
FRONTEND_DIR = Path("frontend")
TODAY_DIR = Path("data/today")
KEEP_DAYS = 14
SITE_FILES = ("index.html", "script.js", "style.css")
STATIC_CONFIG = ('// Generated by build_site.py: static mode (no server). Data comes from ./data/<date>.json\n'
                 'window.SB_CONFIG = { apiBase: "", dataBase: "data" };\n')


async def refresh_results(day, state, days=1):
    added = await shared_refresh(day, state, fetch_football_data, days)
    print(f"Results refresh: {added} new finished matches added")
    return added


def sync_site():
    SITE_DIR.mkdir(parents=True, exist_ok=True)
    for name in SITE_FILES:
        shutil.copy(FRONTEND_DIR / name, SITE_DIR / name)
    config = SITE_DIR / "config.js"
    if not config.exists():                 # never overwrite: you may have set your API address in it
        config.write_text(STATIC_CONFIG, encoding="utf-8")
    (SITE_DIR / ".nojekyll").write_text("", encoding="utf-8")


def write_index(today):
    data_dir = SITE_DIR / "data"
    dates = []
    for f in data_dir.glob("????-??-??.json"):
        try:
            d = date.fromisoformat(f.stem)
        except ValueError:
            continue
        if (today - d).days > KEEP_DAYS:
            f.unlink()                      # keep the repo small
        else:
            dates.append(d.isoformat())
    index = {"generated_at": datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z"),
             "today": today.isoformat(), "dates": sorted(dates)}
    (data_dir / "index.json").write_text(json.dumps(index, indent=1), encoding="utf-8")
    return index


async def main_async(args):
    try:
        zone = get_tz(args.tz)
    except ValueError as exc:
        raise SystemExit(str(exc))
    today = date.fromisoformat(args.today) if args.today else datetime.now(zone).date()
    state = get_state()

    if not args.no_refresh:
        if await refresh_results(today, state, args.refresh_days):
            get_state.cache_clear()
            state = get_state()

    dates = [date.fromisoformat(d) for d in args.dates] if args.dates else [today, today + timedelta(days=1)]
    (SITE_DIR / "data").mkdir(parents=True, exist_ok=True)
    built = 0
    for d in dates:
        try:
            payload, rows = await build_day_payload(d, zone, args.tz, "auto", state, fetch_football_data, TODAY_DIR)
        except DayUnavailable as exc:
            print(f"{d}: skipped ({exc.detail})")
            continue
        (SITE_DIR / "data" / f"{d}.json").write_text(json.dumps(payload, ensure_ascii=False), encoding="utf-8")
        built += 1
        s = payload["summary"]
        print(f"{d}: {s['predicted']} matches in {s['leagues']} competitions "
              f"({payload['source']}; history through {payload['data_through']})")
        if d == today and write_predictions_csv(rows, TODAY_DIR / f"predictions_{d}.csv"):
            print(f"   saved {TODAY_DIR / f'predictions_{d}.csv'} (used by score_day.py)")

    sync_site()
    index = write_index(today)
    print(f"Site written to {SITE_DIR}/ ({len(index['dates'])} day(s) available: {', '.join(index['dates'])})")
    return 0 if built or index["dates"] else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dates", nargs="*", help="YYYY-MM-DD days to build (default: today and tomorrow)")
    ap.add_argument("--today", help="override 'today' (testing)")
    ap.add_argument("--tz", default="Africa/Lagos")
    ap.add_argument("--no-refresh", action="store_true")
    ap.add_argument("--refresh-days", type=int, default=1)
    return asyncio.run(main_async(ap.parse_args()))


if __name__ == "__main__":
    sys.exit(main())
